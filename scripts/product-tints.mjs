// Generates lib/product-tints.ts: for every product photo, the hue of its colour and how coloured it is.
// The editorial product card uses it to nudge the pink silk (and the hover beige) toward the product.
// Run after adding or replacing photos in public/images/products:  node scripts/product-tints.mjs
import fs from "node:fs"
import path from "node:path"
import sharp from "sharp"

const DIR = "public/images/products"
const OUT = "lib/product-tints.ts"

const lin = (c) => ((c /= 255) <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
function oklab(r, g, b) {
  const [R, G, B] = [lin(r), lin(g), lin(b)]
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B)
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B)
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B)
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ]
}

const rows = {}
for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith(".webp")).sort()) {
  const { data, info } = await sharp(path.join(DIR, file)).resize(96, 96, { fit: "inside" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  let opaque = 0, colored = 0, sa = 0, sb = 0, sc = 0, sl = 0
  for (let i = 0; i < info.width * info.height; i++) {
    const [r, g, b, a] = [data[i * 4], data[i * 4 + 1], data[i * 4 + 2], data[i * 4 + 3]]
    if (a < 220) continue
    opaque++
    const [L, A, B] = oklab(r, g, b)
    sl += L   // mean lightness of the whole product (black caps and white boxes included): drives the hover backdrop contrast
    const C = Math.hypot(A, B)
    // Skip white/near-white, near-black and greys: only real colour votes.
    if (C < 0.045 || L > 0.95 || L < 0.12) continue
    colored++
    sa += A; sb += B; sc += C   // vector sum of (a, b) and sum of chroma
  }
  const coverage = opaque ? colored / opaque : 0
  const hue = (Math.atan2(sb, sa) * 180) / Math.PI
  // coherence: 1 when every coloured pixel shares one hue, ~0 when they cancel out (a multicolour label)
  const coherence = sc ? Math.hypot(sa, sb) / sc : 0
  const meanC = colored ? sc / colored : 0
  const strength = coverage < 0.08 ? 0 : Math.min(1, coverage / 0.3) * coherence * Math.min(1, meanC / 0.12)
  rows["/images/products/" + file] = [Math.round((hue + 360) % 360), Math.round(strength * 100) / 100, Math.round((opaque ? sl / opaque : 0.7) * 100) / 100]
}

const body = Object.entries(rows).map(([k, v]) => `  ${JSON.stringify(k)}: [${v[0]}, ${v[1]}, ${v[2]}],`).join("\n")
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/product-tints.mjs — do not edit by hand.\n// image path → [hue in OKLCH degrees, strength 0–1, mean lightness 0–1]. Strength 0 = neutral product (black, white, grey): no tint.\nexport const PRODUCT_TINTS: Record<string, readonly [number, number, number]> = {\n${body}\n}\n`,
)
console.log(Object.keys(rows).length, "photos →", OUT)
